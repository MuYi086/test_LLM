def story(identifier, split, category, source, script, facts, steady=False):
    """事实片段与每条直接对白都保留独立检查，不以格式代替语义审阅。"""
    from voxcpm_adapter import LINE

    rows = [LINE.fullmatch(line).groups() for line in script.splitlines()]
    roles = list(dict.fromkeys(["旁白", *(r[0] for r in rows)]))
    speeches = Counter((r[0], r[2]) for r in rows if r[0] != "旁白")
    return {
        "id": identifier,
        "source_id": "original_voxcpm_v2_" + identifier,
        "split": split,
        "category": category,
        "source_text": source,
        "allowed_roles": roles,
        "tone_policy": "steady" if steady else "contextual",
        "review": "agent_authored_and_semantically_reviewed; user_audio_decision_pending",
        "fact_checks": [{"source": text, "target": text, "role": "旁白"} for text in facts],
        "speech_checks": [
            {"speaker": speaker, "text": text, "count": count}
            for (speaker, text), count in speeches.items()
        ],
        "messages": [
            {"role": "system", "content": SYSTEM},
            {"role": "user", "content": "改写下面的文本：\n" + source},
            {"role": "assistant", "content": script},
        ],
    }


def general(identifier, split, source, target):
    """普通任务保持简洁正文，防止标签侵入非小说问答。"""
    return {
        "id": identifier,
        "source_id": "original_voxcpm_v2_" + identifier,
        "split": split,
        "category": "general",
        "source_text": source,
        "messages": [
            {"role": "system", "content": "你是一个简洁准确的中文助手。"},
            {"role": "user", "content": source},
            {"role": "assistant", "content": target},
        ],
    }


